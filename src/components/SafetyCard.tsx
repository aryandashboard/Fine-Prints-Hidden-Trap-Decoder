'use client';

import React, { useState } from 'react';
import {
  AlertTriangle, DollarSign, MessageSquare,
  Copy, Download, ShieldAlert, Check, RefreshCw,
} from 'lucide-react';
import styles from './SafetyCard.module.css';

interface RedFlag {
  clause: string;
  explanation: string;
  riskLevel: 'Low' | 'Medium' | 'High';
}

interface HiddenCost {
  fee: string;
  whenApplies: string;
  clarify: string;
}

export interface SafetyCardData {
  redFlags: RedFlag[];
  hiddenCosts: HiddenCost[];
  askScript: string[];
}

interface SafetyCardProps {
  data: SafetyCardData;
  onNewScan?: () => void;
}

export default function SafetyCard({ data, onNewScan }: SafetyCardProps) {
  const [copied, setCopied] = useState(false);
  const highRiskCount = data.redFlags.filter(f => f.riskLevel === 'High').length;

  const handleCopy = async () => {
    const lines = [
      '━━━ SAFETY CARD SUMMARY ━━━',
      '',
      '🚩 RED FLAG CLAUSES',
      ...data.redFlags.map(f => `  [${f.riskLevel}] ${f.clause}\n  → ${f.explanation}`),
      '',
      '💰 HIDDEN MONEY COSTS',
      ...data.hiddenCosts.map(c => `  ${c.fee}\n  When: ${c.whenApplies}\n  Clarify: ${c.clarify}`),
      '',
      '💬 ASK BEFORE SIGNING',
      ...data.askScript.map((s, i) => `  ${i + 1}. ${s}`),
      '',
      '━━━ Generated by Fine Prints Decoder ━━━',
    ];
    await navigator.clipboard.writeText(lines.join('\n'));
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => window.print();

  const getBadgeClass = (level: string) => {
    if (level === 'High') return styles.badgeHigh;
    if (level === 'Medium') return styles.badgeMedium;
    return styles.badgeLow;
  };

  const totalIssues = data.redFlags.length + data.hiddenCosts.length;

  return (
    <div className={styles.container}>

      {/* ─── Header ────────────────────────────────── */}
      <div className={styles.header}>
        <div>
          <h2 className={styles.title}>Safety Card</h2>
          <p className={styles.subtitle}>
            {totalIssues > 0
              ? `${totalIssues} issue${totalIssues !== 1 ? 's' : ''} found · ${highRiskCount} high risk`
              : 'No significant issues found'}
          </p>
        </div>
        <div className={styles.actions}>
          <button id="copy-card-btn" className={styles.iconBtn} onClick={handleCopy} title="Copy to clipboard">
            {copied ? <Check size={15} /> : <Copy size={15} />}
            {copied ? 'Copied!' : 'Copy'}
          </button>
          <button id="save-pdf-btn" className={styles.iconBtn} onClick={handleDownload} title="Save as PDF">
            <Download size={15} /> PDF
          </button>
          {onNewScan && (
            <button id="new-scan-btn" className={styles.iconBtnPrimary} onClick={onNewScan} title="Analyze another document">
              <RefreshCw size={15} /> New Scan
            </button>
          )}
        </div>
      </div>

      {/* ─── Critical warning ───────────────────────── */}
      {highRiskCount >= 3 && (
        <div className={styles.seriousWarning}>
          <ShieldAlert size={20} style={{ flexShrink: 0 }} />
          <span>
            <strong>{highRiskCount} High-Risk clauses detected.</strong> We strongly recommend having a qualified legal professional review this document before you sign.
          </span>
        </div>
      )}

      {/* ─── Red Flags ──────────────────────────────── */}
      <div className={`${styles.section} ${styles.redFlags}`}>
        <div className={styles.sectionTitle}>
          <span className={styles.sectionIcon} style={{ background: 'var(--danger)', color: 'white' }}>
            <AlertTriangle size={14} />
          </span>
          Red Flag Clauses
          {data.redFlags.length > 0 && (
            <span className={styles.count}>{data.redFlags.length}</span>
          )}
        </div>
        {data.redFlags.length > 0 ? (
          <ul className={styles.list}>
            {data.redFlags.map((flag, index) => (
              <li key={index} className={styles.cardItem}>
                <div className={styles.itemHeader}>
                  <span className={styles.clauseText}>&ldquo;{flag.clause}&rdquo;</span>
                  <span className={`${styles.badge} ${getBadgeClass(flag.riskLevel)}`}>{flag.riskLevel}</span>
                </div>
                <div className={styles.explanation}>{flag.explanation}</div>
              </li>
            ))}
          </ul>
        ) : (
          <div className={styles.emptyState}>✓ No immediate red flags detected, but always read carefully.</div>
        )}
      </div>

      {/* ─── Hidden Costs ──────────────────────────── */}
      <div className={`${styles.section} ${styles.money}`}>
        <div className={styles.sectionTitle}>
          <span className={styles.sectionIcon} style={{ background: 'var(--warning)', color: 'white' }}>
            <DollarSign size={14} />
          </span>
          Hidden Money Costs
          {data.hiddenCosts.length > 0 && (
            <span className={styles.count}>{data.hiddenCosts.length}</span>
          )}
        </div>
        {data.hiddenCosts.length > 0 ? (
          <ul className={styles.list}>
            {data.hiddenCosts.map((cost, index) => (
              <li key={index} className={styles.cardItem}>
                <div className={styles.costLabel}>Fee</div>
                <div className={styles.costValue}>{cost.fee}</div>
                {cost.whenApplies && (
                  <>
                    <div className={styles.costLabel} style={{ marginTop: '0.5rem' }}>When it applies</div>
                    <div className={styles.costValue}>{cost.whenApplies}</div>
                  </>
                )}
                {cost.clarify && (
                  <>
                    <div className={styles.costLabel} style={{ marginTop: '0.5rem' }}>Ask to clarify</div>
                    <div className={styles.costValue}>{cost.clarify}</div>
                  </>
                )}
              </li>
            ))}
          </ul>
        ) : (
          <div className={styles.emptyState}>✓ No clear hidden costs found in this excerpt.</div>
        )}
      </div>

      {/* ─── Ask Script ─────────────────────────────── */}
      <div className={`${styles.section} ${styles.script}`}>
        <div className={styles.sectionTitle}>
          <span className={styles.sectionIcon} style={{ background: 'var(--success)', color: 'white' }}>
            <MessageSquare size={14} />
          </span>
          Ask Before Signing
        </div>
        {data.askScript.length > 0 ? (
          <ol className={styles.scriptList}>
            {data.askScript.map((item, index) => (
              <li key={index} className={styles.scriptItem}>{item}</li>
            ))}
          </ol>
        ) : (
          <div className={styles.emptyState}>✓ No specific clarification questions needed based on this text.</div>
        )}
      </div>

    </div>
  );
}
